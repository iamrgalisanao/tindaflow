import { useState } from 'react';
import SlideOver from '../SlideOver';
import { failureMessage, fieldErrors, request } from '../catalog/catalogApi';
import { EMPLOYEE_TYPES, employeeBody, joinName, typeLabel, validateEmployee } from './employeeConfig';

const inputClass = (error) =>
    `min-h-11 w-full rounded-md border bg-slate-950 px-3 py-1.5 text-sm text-slate-100 placeholder:text-slate-600 focus:outline-none focus:ring-1 lg:min-h-0 ${
        error ? 'border-rose-500 focus:ring-rose-500' : 'border-slate-700 focus:border-emerald-500 focus:ring-emerald-500'
    }`;

function Field({ id, label, required, hint, error, children }) {
    return (
        <div>
            <label htmlFor={id} className="mb-1 block text-xs text-slate-400">
                {label} {required && <span className="text-emerald-400">*</span>}
            </label>
            {children}
            {error ? (
                <p role="alert" className="mt-1 font-mono text-[11px] text-rose-400">
                    &#9888; {error}
                </p>
            ) : (
                hint && <p className="mt-1 text-[11px] text-slate-500">{hint}</p>
            )}
        </div>
    );
}

/**
 * Slide-over for employeeCreate / employeeUpdate. The code is generated by the server and is never typed: a new employee is
 * created, then the slide-over shows the code that was issued (it is also what the QR / ID card carries). The type is chosen once
 * and cannot be changed afterwards, because it fixes the code's prefix and the credit limit.
 */
export default function EmployeeFormPanel({ employee, onSaved, onClose, onUnauthorized }) {
    const editing = Boolean(employee);
    const [values, setValues] = useState({
        employee_type: employee?.employee_type ?? '',
        first_name: employee?.first_name ?? '',
        middle_name: employee?.middle_name ?? '',
        last_name: employee?.last_name ?? '',
    });
    const [errors, setErrors] = useState({});
    const [formError, setFormError] = useState(null);
    const [saving, setSaving] = useState(false);
    const [created, setCreated] = useState(null);

    function set(field, value) {
        setValues((prior) => ({ ...prior, [field]: value }));
        setErrors((prior) => ({ ...prior, [field]: undefined }));
    }

    async function submit(event) {
        event.preventDefault();
        const clientErrors = validateEmployee(values, editing);
        if (Object.keys(clientErrors).length > 0) {
            setErrors(clientErrors);
            return;
        }
        setSaving(true);
        setFormError(null);
        const result = await request(editing ? `/api/v1/employees/${employee.id}` : '/api/v1/employees', {
            method: editing ? 'PATCH' : 'POST',
            body: employeeBody(values, editing),
        });
        setSaving(false);
        if (result.ok) {
            if (editing) {
                onSaved(result.body, true);
            } else {
                setCreated(result.body);
                onSaved(result.body, false, { keepOpen: true });
            }
            return;
        }
        if (result.status === 401) {
            onUnauthorized();
            return;
        }
        const serverErrors = fieldErrors(result);
        if (Object.keys(serverErrors).length > 0) {
            setErrors(serverErrors);
            return;
        }
        setFormError(failureMessage(result, 'The employee could not be saved.'));
    }

    function addAnother() {
        setCreated(null);
        setValues({ employee_type: values.employee_type, first_name: '', middle_name: '', last_name: '' });
    }

    const footer = created ? (
        <div className="flex items-center justify-between border-t border-slate-800 bg-slate-950/80 px-5 py-3">
            <button type="button" onClick={onClose} className="min-h-11 rounded px-3 text-sm text-slate-300 hover:text-white lg:min-h-0">
                Done
            </button>
            <button type="button" onClick={addAnother} className="min-h-11 rounded-md bg-emerald-500 px-5 py-2 text-sm font-semibold text-slate-950 hover:bg-emerald-400 lg:min-h-0">
                Add another
            </button>
        </div>
    ) : (
        <div className="flex items-center justify-between border-t border-slate-800 bg-slate-950/80 px-5 py-3">
            <button type="button" onClick={onClose} className="min-h-11 rounded px-3 text-sm text-slate-300 hover:text-white lg:min-h-0">
                Cancel
            </button>
            <button
                type="submit"
                form="employee_form"
                disabled={saving}
                className="min-h-11 rounded-md bg-emerald-500 px-5 py-2 text-sm font-semibold text-slate-950 hover:bg-emerald-400 disabled:opacity-50 lg:min-h-0"
            >
                {saving ? 'Saving…' : editing ? 'Save changes' : 'Create employee'}
            </button>
        </div>
    );

    return (
        <SlideOver titleId="employee_panel_title" title={editing ? 'Edit employee' : 'New employee'} badge={editing ? employee.employee_code : null} onClose={onClose} footer={footer}>
            {created ? (
                <div className="flex-1 space-y-4 overflow-y-auto px-5 py-4" role="status">
                    <p className="text-sm text-slate-300">
                        {joinName(created.first_name, created.middle_name, created.last_name)} is enrolled as {typeLabel(created.employee_type)}. Their code is:
                    </p>
                    <p className="rounded-md border border-emerald-800 bg-emerald-950/30 px-4 py-4 text-center font-mono text-3xl font-bold tracking-widest text-emerald-300">
                        {created.employee_code}
                    </p>
                    <p className="text-sm text-slate-400">
                        The code was made by the system and never changes. Print the ID card from <span className="text-slate-200">Print ID cards</span>.
                    </p>
                </div>
            ) : (
                <form id="employee_form" onSubmit={submit} noValidate className="flex-1 space-y-4 overflow-y-auto px-5 py-4">
                    {formError && (
                        <p role="alert" className="rounded-md border border-rose-800 bg-rose-950/40 px-3 py-2 text-sm text-slate-100">
                            {formError}
                        </p>
                    )}

                    {editing ? (
                        <div className="rounded-md border border-slate-800 bg-slate-950/50 px-3 py-2 text-sm text-slate-300">
                            <p>
                                Code <span className="font-mono text-emerald-300">{employee.employee_code}</span> &middot; {typeLabel(employee.employee_type)}
                            </p>
                            <p className="mt-1 text-[11px] text-slate-500">The code and the type cannot be changed. To stop someone using credit, deactivate them.</p>
                        </div>
                    ) : (
                        <fieldset>
                            <legend className="mb-1 text-xs text-slate-400">
                                Type <span className="text-emerald-400">*</span>
                            </legend>
                            {errors.employee_type && (
                                <p role="alert" className="mb-1 font-mono text-[11px] text-rose-400">
                                    &#9888; {errors.employee_type}
                                </p>
                            )}
                            <div className="grid grid-cols-2 gap-2">
                                {EMPLOYEE_TYPES.map((entry) => (
                                    <label
                                        key={entry.id}
                                        className={`flex cursor-pointer items-center gap-2 rounded-md border p-2.5 text-sm ${
                                            values.employee_type === entry.id ? 'border-emerald-500 bg-emerald-950/20 text-slate-100' : 'border-slate-700 bg-slate-950/40 text-slate-300 hover:bg-slate-800/60'
                                        }`}
                                    >
                                        <input type="radio" name="employee_type" value={entry.id} checked={values.employee_type === entry.id} onChange={() => set('employee_type', entry.id)} className="accent-emerald-500" />
                                        {entry.label}
                                    </label>
                                ))}
                            </div>
                        </fieldset>
                    )}

                    <Field id="employee_first_name" label="First name" required error={errors.first_name}>
                        <input id="employee_first_name" type="text" autoComplete="off" value={values.first_name} aria-invalid={Boolean(errors.first_name)} onChange={(event) => set('first_name', event.target.value)} className={inputClass(errors.first_name)} />
                    </Field>
                    <Field id="employee_middle_name" label="Middle name" error={errors.middle_name}>
                        <input id="employee_middle_name" type="text" autoComplete="off" value={values.middle_name} onChange={(event) => set('middle_name', event.target.value)} className={inputClass(errors.middle_name)} />
                    </Field>
                    <Field id="employee_last_name" label="Last name" required error={errors.last_name}>
                        <input id="employee_last_name" type="text" autoComplete="off" value={values.last_name} aria-invalid={Boolean(errors.last_name)} onChange={(event) => set('last_name', event.target.value)} className={inputClass(errors.last_name)} />
                    </Field>
                    {!editing && <p className="text-[11px] text-slate-500">The code (TSC00001 or SUB00001) is made for you when you save.</p>}
                </form>
            )}
        </SlideOver>
    );
}
